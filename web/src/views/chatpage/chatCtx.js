/** 按名从作用域对象取出一份上下文（缺键说明清单与作用域漂了，直接抛，别静默 undefined）。 */
export function pickChatCtx (scope) {
  const out = {}
  const missing = []
  for (const k of CHAT_CTX_KEYS) {
    if (k in scope) out[k] = scope[k]
    else missing.push(k)
  }
  if (missing.length) throw new Error('chatCtx 缺键: ' + missing.join(', '))
  return out
}
