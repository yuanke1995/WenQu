package com.wenqu.ai.agent.chat;

/**
 * 「什么该写成文件、什么该留在回答里」这条交付口径的唯一出处。
 *
 * <p><b>为什么要单独说一遍</b>：产物工具的说明书只写了「想下载/预览时调用」，参数说明又把结构化数据
 * 指向 {@code .json}，于是用户说「给我一份 JSON，我导入」时模型会顺手落成产物卡——用户拿到的是下载
 * 动作，而不是一段能直接复制的正文。沙盒那一路的 {@code deliver_artifact} 说明来自框架，
 * 问渠改不动，只能在系统提示词里统一压住。
 */
public final class ArtifactPrompt {

    private ArtifactPrompt() {
    }

    /** 挂进系统提示词的一条交付口径：能被粘贴走的片段留在正文，文件只收成品；统计图走 echarts 围栏。 */
    public static String guidance() {
        return "\n【交付形态】用户要拿去复制、粘贴或导入的片段（配置、代码、结构化数据），直接放在回答的"
                + "代码块里；只有想下载或预览的成品文件才交付成文件。内容没把握时不要做成文件充数，"
                + "先说清缺什么。\n"
                + "\n【统计图】用户要图表 / 可视化 / 多维展示 / 看趋势 / 做对比时，默认在聊天里出图：用 ```echarts 围栏，"
                + "围栏内放一份完整可解析的 ECharts option JSON（不带注释、尾逗号与 JS 函数，一张图一个围栏），"
                + "界面会原位渲染。\n"
                + "用户点名要「产物 / 交付物 / HTML / 报告页 / 可下载、可分享」时，改走产物交付：把统计图直接写进"
                + "那页 HTML（页面内用 ECharts 渲染），正文只给要点与访问入口，不要再拆成 echarts 围栏；"
                + "两样都要时，正文出图 + 同时交付一页 HTML 产物。\n";
    }
}
